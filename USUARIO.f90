SUBROUTINE USUARIO(MC, ISLOT)

    INCLUDE 'COMON4.INS'
    INTEGER I, ISLOT, J, K, L, M, IERR
    REAL V_INPUT1, V_GAIN1, V_OUTPUT1

    J = STRTIN(1, ISLOT) ! STARTING 'CON'
    K = STRTIN(2, ISLOT) ! STARTING 'STATE'
    L = STRTIN(3, ISLOT) ! STARTING 'VAR'
    M = STRTIN(4, ISLOT) ! STARTING 'ICON'

    IF (MIDTRM) RETURN


    SELECT CASE(MODE)
    CASE(1) ! INCIALIZACION
        V_OUTPUT1 = OUTPUT(1)
        V_GAIN1 = V_OUTPUT1
        V_INPUT1 = V_GAIN1 / 1.0
        ! Input INPUT1 initialized to V_INPUT1
    CASE(2) ! CALCULO DE DERIVADAS
        V_INPUT1 = INPUT(1)
        V_GAIN1 = V_INPUT1 * 1.0
        V_OUTPUT1 = V_GAIN1
    CASE(3) ! CALCULO DE LAS SALIDAS
        V_INPUT1 = INPUT(1)
        V_GAIN1 = V_INPUT1 * 1.0
        VAR(1) = V_GAIN1
        V_OUTPUT1 = V_GAIN1
    CASE(4) ! ESPACIOS PARA INTEGRACION
        NINTEG=MAX(NINTEG, K + 0)
    CASE(5)
    CASE(6)
    CASE(7)
    CASE(8) ! DESCRIPCION DE LOS CONS
        CON_DSCRPT(J+0) = 'GAIN1 GAIN'
    

    END SELECT
END SUBROUTINE
